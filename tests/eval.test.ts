// Relevance eval harness (blueprint M2): labelled queries over a synthetic public corpus, hit@1 / hit@5 / MRR.
// Runs in CI against the real engine; thresholds are floors just under the recorded baseline (docs/eval/baseline.md),
// so a ranking regression fails. EVAL_WRITE=1 npx vitest run tests/eval.test.ts regenerates the baseline and query snapshot.
import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { generateCorpus } from './support/corpus';
import { loadCorpus } from './support/load';
import { evaluate, generateQueries } from './eval/queries';
import { newStore, NOW } from './helpers/engine';

const PAGES = 5000;

describe('relevance eval (synthetic corpus, 20% Greek)', () => {
  it('meets the recorded baseline floors', async () => {
    const docs = generateCorpus({ pages: PAGES, now: NOW });
    const { store } = await newStore();
    loadCorpus(store, docs);
    const queries = generateQueries(docs);
    const m = evaluate(store, docs, queries, NOW);

    if (process.env.EVAL_WRITE) {
      mkdirSync('docs/eval', { recursive: true });
      writeFileSync('tests/eval/queries.jsonl', `${queries.map((q) => JSON.stringify(q)).join('\n')}\n`);
      const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
      const rows = Object.entries(m).map(([k, v]) => `| ${k} | ${v.n} | ${pct(v.hit1)} | ${pct(v.hit5)} | ${v.mrr.toFixed(3)} | ${v.suggestionRate === undefined ? '' : pct(v.suggestionRate)} |`);
      writeFileSync(
        'docs/eval/baseline.md',
        `# Relevance baseline (M2)\n\nGenerated by \`EVAL_WRITE=1 npx vitest run tests/eval.test.ts\`. Corpus: ${PAGES} synthetic pages (deterministic, 20% Greek with tonos, Zipf vocabulary, mean 5.4 KB), loaded as history + Deep Search content. ${queries.length} labelled queries (\`tests/eval/queries.jsonl\`). Expected page = the page the query was derived from.\n\n| query kind | n | hit@1 | hit@5 | MRR | "did you mean" hit |\n|---|---|---|---|---|---|\n${rows.join('\n')}\n\nCaveats: synthetic word-salad text measures plumbing (folding, prefix, phrase, filters, ranking mechanics), not real-world relevance; the real eval set (own browsing + testers, never committed) arrives with M10. Typo queries (one deleted character) cannot match by design (no fuzzy retrieval in V1): the engine offers a "did you mean" suggestion instead, shown in the last column.\n`,
      );
    }

    // floors sit a few points under the recorded baseline (docs/eval/baseline.md): a ranking/folding regression fails CI
    const all = m['ALL (excluding typo)'];
    expect(all?.hit5).toBeGreaterThanOrEqual(0.85);
    expect(all?.hit1).toBeGreaterThanOrEqual(0.65);
    expect(all?.mrr).toBeGreaterThanOrEqual(0.75);
    expect(m.title?.hit5).toBeGreaterThanOrEqual(0.95);
    expect(m['body-two-words']?.hit5).toBeGreaterThanOrEqual(0.95);
    expect(m['greek-unaccented']?.hit5).toBeGreaterThanOrEqual(0.85); // accent-less Greek must find accented text
    expect(m.phrase?.hit1).toBeGreaterThanOrEqual(0.95);
    expect(m['site-and-word']?.hit5).toBeGreaterThanOrEqual(0.95);
    expect(m.prefix?.hit5).toBeGreaterThanOrEqual(0.3); // inherently ambiguous: a selective prefix still matches several pages
    expect(m.typo?.suggestionRate).toBeGreaterThanOrEqual(0.55);
    expect(store.integrityCheck().ok).toBe(true);
  }, 120_000);
});
